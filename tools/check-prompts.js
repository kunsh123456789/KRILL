#!/usr/bin/env node
/* Validate data/prompts.json with the game's own matching code, then write
 * data/prompts.js (the copy the game loads when index.html is opened from disk).
 *
 *   node tools/check-prompts.js            validate + regenerate data/prompts.js
 *   node tools/check-prompts.js --check    validate only
 *   node tools/check-prompts.js --verbose  also list typo-ambiguous answer pairs
 */
'use strict';
const fs = require('fs');
const path = require('path');
const game = require('../game.js');

const root = path.join(__dirname, '..');
const jsonPath = path.join(root, 'data', 'prompts.json');
const jsPath = path.join(root, 'data', 'prompts.js');
const args = new Set(process.argv.slice(2));

const errors = [];
const warnings = [];
let prompts;
try {
  prompts = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
} catch (e) {
  console.error(`Could not parse ${jsonPath}: ${e.message}`);
  process.exit(1);
}

if (!Array.isArray(prompts)) errors.push('Top level must be an array of prompts.');
const validTiers = Object.keys(game.CONFIG.tiers).filter((t) => t !== 'invalid' && t !== 'timeout');
const seenIds = new Set();

for (const p of prompts || []) {
  const where = `prompt ${p && p.id} (${p && p.prompt})`;
  if (!Number.isInteger(p.id)) errors.push(`${where}: "id" must be an integer.`);
  else if (seenIds.has(p.id)) errors.push(`${where}: duplicate id.`);
  seenIds.add(p.id);
  if (typeof p.prompt !== 'string' || !p.prompt.trim()) errors.push(`${where}: missing "prompt" text.`);
  if (!Array.isArray(p.answers) || !p.answers.length) { errors.push(`${where}: needs a non-empty "answers" array.`); continue; }
  if (p.optionalWords !== undefined && !Array.isArray(p.optionalWords)) errors.push(`${where}: "optionalWords" must be an array.`);

  const tierCounts = {};
  for (const a of p.answers) {
    if (typeof a.text !== 'string' || !game.normalize(a.text)) errors.push(`${where}: answer with empty "text".`);
    if (!validTiers.includes(a.tier)) errors.push(`${where}: "${a.text}" has unknown tier "${a.tier}" (use ${validTiers.join(', ')}).`);
    if (a.aliases !== undefined && !Array.isArray(a.aliases)) errors.push(`${where}: "${a.text}" aliases must be an array.`);
    tierCounts[a.tier] = (tierCounts[a.tier] || 0) + 1;
  }
  for (const t of game.CONFIG.rarityOrder) if (!tierCounts[t]) warnings.push(`${where}: no "${t}" answers.`);
  if (p.answers.length < 20) warnings.push(`${where}: only ${p.answers.length} answers.`);

  const index = game.buildIndex(p);
  for (const c of index.conflicts) errors.push(`${where}: "${c.a}" and "${c.b}" both match the input "${c.key}".`);

  // Every answer must match its own text and aliases.
  for (const a of p.answers) {
    for (const form of [a.text].concat(a.aliases || [])) {
      const m = game.matchAnswer(p, index, form);
      if (!m || m.answer !== a) errors.push(`${where}: typing "${form}" does not select "${a.text}".`);
    }
  }

  if (args.has('--verbose')) {
    const { minLength, maxDistance } = game.CONFIG.fuzzy;
    const keys = index.keys.filter((k) => k.length >= minLength);
    for (let i = 0; i < keys.length; i++) {
      for (let j = i + 1; j < keys.length; j++) {
        const a = index.exact.get(keys[i]);
        const b = index.exact.get(keys[j]);
        if (a !== b && game.editDistance(keys[i], keys[j], maxDistance) <= maxDistance) {
          warnings.push(`${where}: "${keys[i]}" (${a.text}) and "${keys[j]}" (${b.text}) are one typo apart.`);
        }
      }
    }
  }
}

if ((prompts || []).length < game.CONFIG.roundsPerRun) errors.push(`Need at least ${game.CONFIG.roundsPerRun} prompts.`);

for (const w of warnings) console.warn(`warning: ${w}`);
for (const e of errors) console.error(`error: ${e}`);
const answerCount = prompts.reduce((s, p) => s + (p.answers ? p.answers.length : 0), 0);
if (errors.length) {
  console.error(`\n${errors.length} error(s). data/prompts.js was not updated.`);
  process.exit(1);
}
console.log(`OK: ${prompts.length} prompts, ${answerCount} answers.`);

if (!args.has('--check')) {
  const banner = '/* Generated by tools/check-prompts.js from data/prompts.json. Do not edit by hand.\n' +
    ' * Used only when index.html is opened directly from disk (file://), where fetch() is blocked. */\n';
  fs.writeFileSync(jsPath, `${banner}window.DEEPRECALL_PROMPTS = ${JSON.stringify(prompts)};\n`);
  console.log(`Wrote ${path.relative(root, jsPath)}.`);
}
